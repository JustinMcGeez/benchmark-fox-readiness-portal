-- ACCESS MODEL (the boundary 004 enforces; see docs/backend/supabase-architecture.md §11):
--
--   Roles (profiles.role is the authoritative primary role):
--     * benchmark_fox_admin       -> full read/write on ALL tenant tables.
--     * benchmark_fox_consultant  -> read/write ONLY clients present in their
--                                    client_assignments rows.
--     * client_executive /
--       client_it_owner /
--       readonly_viewer           -> READ-ONLY on their single assigned client;
--                                    no access to other clients or the clients list.
--     * evidence_uploader         -> read assigned client + insert/update evidence
--                                    METADATA for that client only; no assessments.
--
--   Reference tables (control_families, controls, source_references,
--   control_source_references): readable by any authenticated user; writable by
--   NOBODY via anon/auth keys — only the service_role seed script (which bypasses
--   RLS) writes them.
--
--   Helper predicates (defined in 004, SECURITY DEFINER, execute → authenticated):
--     current_profile_id()           -- profile id for auth.uid()
--     has_role(app_role)             -- caller's profiles.role = target
--     is_bf_admin() / is_bf_consultant()
--     is_assigned_to_client(client)  -- READ gate: admin OR any assignment
--     can_write_client(client)       -- WRITE gate: admin OR (consultant AND assigned)
--
--   No tenant-table policy uses auth.uid() directly — every one roots in the
--   helpers above, so cross-client leakage has a single, testable choke point.
--
--   audit_events is APPEND-ONLY: INSERT allowed for a caller's accessible
--   clients; no UPDATE/DELETE policy exists for any non-service role.
