/* ============================================================
   build-controls.mjs

   Generates src/data/controls.generated.ts from the local source
   dataset data-sources/sp800-171r2.json (NIST SP 800-171 Rev. 2,
   public-domain U.S. Government text).

   Run: node scripts/build-controls.mjs

   Non-official fields (scoreValue, assessmentObjectives, and the
   Benchmark Fox guidance fields) are emitted as null/empty placeholders
   on purpose — they must be filled from official sources or authored by
   Benchmark Fox, never guessed. See README "Official source documents".
   ============================================================ */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

const SRC = resolve(root, 'data-sources/sp800-171r2.json');
const OUT = resolve(root, 'src/data/controls.generated.ts');

const FAMILIES = {
  '1': ['AC', 'Access Control'],
  '2': ['AT', 'Awareness and Training'],
  '3': ['AU', 'Audit and Accountability'],
  '4': ['CM', 'Configuration Management'],
  '5': ['IA', 'Identification and Authentication'],
  '6': ['IR', 'Incident Response'],
  '7': ['MA', 'Maintenance'],
  '8': ['MP', 'Media Protection'],
  '9': ['PS', 'Personnel Security'],
  '10': ['PE', 'Physical Protection'],
  '11': ['RA', 'Risk Assessment'],
  '12': ['CA', 'Security Assessment'],
  '13': ['SC', 'System and Communications Protection'],
  '14': ['SI', 'System and Information Integrity'],
};

/** Short display label derived from the official requirement text. */
function deriveTitle(text) {
  let t = text.split(/[.;:]| - /)[0].trim();
  // cut at the first comma if the lead clause is long
  if (t.length > 60) t = t.split(',')[0].trim();
  if (t.length > 70) t = t.slice(0, 67).trimEnd() + '…';
  return t;
}

function buildControl(req) {
  const idx = req.number.split('.')[1];
  const fam = FAMILIES[idx];
  if (!fam) throw new Error(`Unknown family for ${req.number}`);
  const [familyCode, familyName] = fam;
  const sourceRefs = ['nist-sp-800-171r2', 'nist-sp-800-171a'];
  if (req.level === 'L1') sourceRefs.push('far-52-204-21');
  return {
    id: req.number,
    number: req.number,
    code: `${familyCode}.${req.level}-${req.number}`,
    familyCode,
    familyName,
    level: req.level,
    scoreValue: null, // DoD Assessment Methodology value — not bundled, do not guess
    title: deriveTitle(req.text),
    summary: req.text,
    requirement: req.text,
    explanation: '', // Benchmark Fox to author (placeholder)
    sspGuidance: null,
    poamGuidance: null,
    assessmentObjectives: null, // NIST SP 800-171A — not bundled locally
    sourceRefs,
  };
}

const raw = JSON.parse(readFileSync(SRC, 'utf8'));
const controls = raw.requirements.map(buildControl);

const header = `/* AUTO-GENERATED by scripts/build-controls.mjs — DO NOT EDIT BY HAND.
   Source: data-sources/sp800-171r2.json (NIST SP 800-171 Rev. 2, public domain).
   Requirement text is official NIST text. scoreValue / assessmentObjectives and
   the Benchmark Fox guidance fields are placeholders (null / '') to be filled
   from official sources or authored by Benchmark Fox — never guessed.
   Regenerate: node scripts/build-controls.mjs
   Count: ${controls.length} requirements. */
import type { Control } from './types';

export const GENERATED_CONTROLS: Control[] = ${JSON.stringify(controls, null, 2)};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, header, 'utf8');
console.log(`Wrote ${controls.length} controls -> ${OUT}`);
